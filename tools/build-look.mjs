// Builds one look in the recipe book: looks/<slug>/recipe.json (+ spacing.json) → looks/<slug>/src/.
// The same steps as Fournée's suggested type/build-type.mjs, pointed at a look's folder, plus the two project files
// (face-overrides.css, spacing.css). The look editor runs this on every Save and Revert.
//   node tools/build-look.mjs <slug>        e.g. node tools/build-look.mjs plum-crumb
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { faceOverridesCss } from './editor/face-overrides.mjs';
import { cleanSpacing, spacingCss } from './editor/spacing.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const project = resolve(here, '..');
export const LOOKS = join(project, 'looks');
export const defaultFournee = resolve(process.env.FOURNEE_HOME || join(project, '..', 'fournee'));
const lf = (s) => s.replace(/\r\n/g, '\n');

export function readSpacing(dir) {
  try { return cleanSpacing(JSON.parse(readFileSync(join(dir, 'spacing.json'), 'utf8'))); } catch { return cleanSpacing({}); }
}

export function buildLook(dir, fournee = defaultFournee) {
  const recipeFile = join(dir, 'recipe.json'), src = join(dir, 'src'), out = join(src, 'theme');
  mkdirSync(out, { recursive: true });
  const log = [];
  // type: fontdant.css, mise-type.css, fonts/, recipe.json
  log.push(execFileSync(process.execPath, [join(fournee, 'delivery', 'scripts', 'project.mjs'), recipeFile, out,
    '--base-url', './fonts', '--display', 'swap'], { windowsHide: true, encoding: 'utf8' }).trim());
  // colour: the role defaults plus this recipe's colours
  writeFileSync(join(out, 'frosting.css'), lf(readFileSync(join(fournee, 'frosting', 'dist', 'frosting.css'), 'utf8')));
  const M = createRequire(import.meta.url)(join(fournee, 'delivery', 'dist', 'mise.js'));
  const recipe = JSON.parse(readFileSync(recipeFile, 'utf8'));
  const all = M.css(recipe), cut = all.indexOf('\n/* ');
  writeFileSync(join(out, 'mise-color.css'), `/* ${recipe.name}: colours from Fournée. Generated by tools/build-look.mjs from recipe.json; do not edit. */\n${cut > 0 ? all.slice(0, cut) : all}\n`);
  // project files Fournée doesn't make
  writeFileSync(join(src, 'face-overrides.css'), faceOverridesCss(recipe));
  writeFileSync(join(src, 'spacing.css'), spacingCss(readSpacing(dir)));
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', fournee, 'rev-parse', '--short', 'HEAD'], { windowsHide: true, encoding: 'utf8' }).trim(); } catch {}
  log.push(`${out}: frosting.css, mise-color.css (Fournée ${commit})`);
  return log.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const slug = process.argv[2];
  if (!slug || !existsSync(join(LOOKS, slug, 'recipe.json'))) { console.error('Usage: node tools/build-look.mjs <slug>  (a folder in looks/)'); process.exit(1); }
  console.log(buildLook(join(LOOKS, slug)));
}
