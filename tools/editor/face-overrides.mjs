// Workaround for Fournée bdb656f: a recipe's per-role `face` override is checked but not emitted to CSS
// (https://github.com/fournee/fournee/issues/1). This writes the missing lines to src/face-overrides.css.
// The editor runs it on every save. By hand: node tools/editor/face-overrides.mjs
// Delete this (and the <link> in index.html) once Fournée emits --fd-<role>-family itself.

export function faceOverridesCss(recipe) {
  const roles = (recipe.fontdant && recipe.fontdant.roles) || {};
  const lines = Object.keys(roles).filter((n) => ['display', 'text', 'mono'].includes(roles[n].face))
    .map((n) => `  --fd-${n}-family: var(--fd-face-${roles[n].face});`);
  return `/* Per-style font choices from type/recipe.json. Fournée bdb656f doesn't emit these yet, so the look editor writes them.
   Generated by tools/editor/face-overrides.mjs; do not edit. */
:root {
${lines.join('\n')}
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { readFileSync, writeFileSync } = await import('node:fs');
  const { join, dirname, resolve } = await import('node:path');
  const project = resolve(dirname(new URL(import.meta.url).pathname), '..', '..');
  const css = faceOverridesCss(JSON.parse(readFileSync(join(project, 'type', 'recipe.json'), 'utf8')));
  writeFileSync(join(project, 'src', 'face-overrides.css'), css);
  console.log(css);
}
