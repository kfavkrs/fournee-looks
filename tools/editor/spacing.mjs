// Page spacing for the sample page. Fournée only covers colour and type, so spacing lives in this project:
// type/spacing.json (the values, in rem) → src/spacing.css (--sp-* variables the page's layout uses).
// The look editor writes both on Save. By hand: node tools/editor/spacing.mjs

export const SPACING_FIELDS = [
  { key: 'section', label: 'Between sections', help: 'Space between the page header, the rows of cards and the footer.', def: 2, min: 0.5, max: 8 },
  { key: 'header-top', label: 'Above the header', help: 'Space between the navigation bar and the top of the page header.', def: 3, min: 0.5, max: 8 },
  { key: 'cards', label: 'Between cards', help: 'Gap between cards in the same row.', def: 1, min: 0.25, max: 4 },
  { key: 'card-padding', label: 'Inside cards', help: 'Space between a card’s edge and its contents.', def: 1.5, min: 0.5, max: 4 },
  { key: 'paragraph', label: 'Between paragraphs', help: 'Space after each paragraph inside a card.', def: 1, min: 0.25, max: 3 },
  { key: 'under-hero', label: 'Under the hero line', help: 'Space between the hero line (“Warm Bread, Every Morning”) and the eyebrow below it.', def: 1.5, min: 0, max: 6 },
  { key: 'under-title', label: 'Under the page title', help: 'Space between the page title (Heading extra large) and the intro paragraph.', def: 1, min: 0, max: 4 },
  { key: 'under-eyebrow', label: 'Under eyebrows', help: 'Space between an eyebrow (e.g. “Fresh today”) and the heading below it.', def: 0.5, min: 0, max: 3 },
  { key: 'under-heading', label: 'Under Heading, base', help: 'Space between a base heading and the text below it.', def: 0.5, min: 0, max: 3 },
  { key: 'under-heading-lg', label: 'Under Heading large', help: 'Space between a large heading and the body text below it.', def: 0.5, min: 0, max: 3 },
  { key: 'under-heading-md', label: 'Under Heading medium', help: 'Space between a medium heading and the text below it (e.g. the small body under “Cardamom Morning Bun”).', def: 0.5, min: 0, max: 3 },
];

export function cleanSpacing(sp) {
  const out = {};
  for (const f of SPACING_FIELDS) {
    const v = Number(sp && sp[f.key]);
    out[f.key] = Number.isFinite(v) ? Math.min(f.max, Math.max(f.min, v)) : f.def;
  }
  return out;
}

export function spacingCss(sp) {
  const s = cleanSpacing(sp);
  return `/* Page spacing from type/spacing.json. Generated by tools/editor/spacing.mjs; do not edit. */
:root {
${SPACING_FIELDS.map((f) => `  --sp-${f.key}: ${s[f.key]}rem;`).join('\n')}
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { readFileSync, writeFileSync, existsSync } = await import('node:fs');
  const { join, dirname, resolve } = await import('node:path');
  const project = resolve(dirname(new URL(import.meta.url).pathname), '..', '..');
  const file = join(project, 'type', 'spacing.json');
  const sp = cleanSpacing(existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {});
  if (!existsSync(file)) writeFileSync(file, JSON.stringify(sp, null, 2) + '\n');
  writeFileSync(join(project, 'src', 'spacing.css'), spacingCss(sp));
  console.log(spacingCss(sp));
}
