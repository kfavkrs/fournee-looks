// This project's colour and type from Fournée. Re-run after editing type/recipe.json or after updating Fournée:
//   node type/build-type.mjs [path-to-fournee]        (default: ../fournee beside this project, or FOURNEE_HOME)
// Writes src/theme/ (commit it; never hand-edit it):
//   frosting.css    Frosting's colour roles with their defaults (--fr-*)
//   mise-color.css  this recipe's colours on those roles (+ the high-contrast block)
//   fontdant.css    Fontdant's type roles and steps;  mise-type.css  this recipe's faces, steps and extension roles
//   fonts/          the self-hosted font files the look uses;  recipe.json  the recipe as applied
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const fournee = resolve(process.argv[2] || process.env.FOURNEE_HOME || join(here, '..', '..', 'fournee'));
if (!existsSync(join(fournee, 'delivery', 'scripts', 'project.mjs'))) {
  console.error(`Fournée not found at ${fournee}. Pass its path: node type/build-type.mjs <path-to-fournee>`); process.exit(1);
}
const out = join(here, '..', 'src', 'theme');
const lf = (s) => s.replace(/\r\n/g, '\n');

// type: fontdant.css, mise-type.css, fonts/, recipe.json
console.log(execFileSync(process.execPath, [join(fournee, 'delivery', 'scripts', 'project.mjs'), join(here, 'recipe.json'), out,
  '--base-url', './fonts', '--display', 'swap'], { windowsHide: true, encoding: 'utf8' }).trim());

// colour: the role defaults plus this recipe's colours
writeFileSync(join(out, 'frosting.css'), lf(readFileSync(join(fournee, 'frosting', 'dist', 'frosting.css'), 'utf8')));
const M = createRequire(import.meta.url)(join(fournee, 'delivery', 'dist', 'mise.js'));
const recipe = JSON.parse(readFileSync(join(here, 'recipe.json'), 'utf8'));
const all = M.css(recipe), cut = all.indexOf('\n/* ');
writeFileSync(join(out, 'mise-color.css'), `/* ${recipe.name}: colours from Fournée. Generated by type/build-type.mjs from type/recipe.json; do not edit. */\n${cut > 0 ? all.slice(0, cut) : all}\n`);

let commit = 'unknown';
try { commit = execFileSync('git', ['-C', fournee, 'rev-parse', '--short', 'HEAD'], { windowsHide: true, encoding: 'utf8' }).trim(); } catch {}
console.log(`${out}: frosting.css, mise-color.css (Fournée ${commit})`);
